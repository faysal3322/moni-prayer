class _DuaItem extends StatefulWidget {
  final Map<String, dynamic> item;
  const _DuaItem({required this.item});
  @override
  State<_DuaItem> createState() => _DuaItemState();
}

class _DuaItemState extends State<_DuaItem> {
  bool _exp = false;

  @override
  Widget build(BuildContext context) {
    final color = widget.item['color'] as Color;
    final title = widget.item['title'] as String;
    final count = widget.item['count'] as String;
    final text = widget.item['text'] as String;
    final note = widget.item['note'] as String;

    return Container(
      margin: const EdgeInsets.only(bottom: 12),
      decoration: BoxDecoration(
        color: AppTheme.cardBg,
        borderRadius: BorderRadius.circular(14),
        border: Border.all(color: color.withOpacity(0.5), width: 1.5),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          // হেডার
          GestureDetector(
            onTap: () => setState(() => _exp = !_exp),
            child: Container(
              padding: const EdgeInsets.all(14),
              decoration: BoxDecoration(
                color: color.withOpacity(_exp ? 0.2 : 0.08),
                borderRadius: _exp
                    ? const BorderRadius.only(
                        topLeft: Radius.circular(14),
                        topRight: Radius.circular(14))
                    : BorderRadius.circular(14),
              ),
              child: Row(children: [
                Expanded(
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Text(title,
                          style: TextStyle(
                              color: color,
                              fontSize: 17,
                              fontWeight: FontWeight.bold)),
                      const SizedBox(height: 4),
                      Container(
                        padding: const EdgeInsets.symmetric(
                            horizontal: 10, vertical: 3),
                        decoration: BoxDecoration(
                          color: color.withOpacity(0.15),
                          borderRadius: BorderRadius.circular(20),
                        ),
                        child: Text(count,
                            style: TextStyle(
                                color: color,
                                fontSize: 13,
                                fontWeight: FontWeight.w600)),
                      ),
                    ],
                  ),
                ),
                Icon(_exp ? Icons.expand_less : Icons.expand_more,
                    color: color, size: 26),
              ]),
            ),
          ),

          // বিষয়বস্তু
          if (_exp)
            Padding(
              padding: const EdgeInsets.fromLTRB(14, 0, 14, 14),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.stretch,
                children: [
                  const SizedBox(height: 10),
                  // দোয়ার টেক্সট
                  Container(
                    width: double.infinity,
                    padding: const EdgeInsets.all(16),
                    decoration: BoxDecoration(
                      color: color.withOpacity(0.06),
                      borderRadius: BorderRadius.circular(12),
                      border: Border.all(color: color.withOpacity(0.3)),
                    ),
                    child: Text(
                      text,
                      style: const TextStyle(
                        color: AppTheme.textPrimary,
                        fontSize: 20,
                        height: 2.2,
                        fontWeight: FontWeight.w500,
                      ),
                    ),
                  ),

                  // নোট
                  if (note.isNotEmpty) ...[
                    const SizedBox(height: 10),
                    Container(
                      padding: const EdgeInsets.all(12),
                      decoration: BoxDecoration(
                        color: const Color(0xFFE65100).withOpacity(0.08),
                        borderRadius: BorderRadius.circular(10),
                        border: Border.all(
                            color: const Color(0xFFE65100).withOpacity(0.3)),
                      ),
                      child: Text(
                        note,
                        style: const TextStyle(
                          color: AppTheme.textSecondary,
                          fontSize: 15,
                          height: 1.8,
                        ),
                      ),
                    ),
                  ],

                  // কপি বাটন
                  const SizedBox(height: 10),
                  GestureDetector(
                    onTap: () {
                      Clipboard.setData(ClipboardData(text: text));
