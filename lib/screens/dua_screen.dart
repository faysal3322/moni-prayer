                            SizedBox(width: 4),
                            Text('কপি', style: TextStyle(color: AppTheme.accent, fontSize: 12)),
                          ]),
                        ),
                      ),
                    ],
                  ),
                ],
              ),
            ),
        ],
      ),
    );
  }
}
