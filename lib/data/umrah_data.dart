class UmrahDua {
  final String id;
  final String title;
  final String arabic;
  final String translit;
  final String meaning;
  final String note;

  const UmrahDua({
    required this.id,
    required this.title,
    required this.arabic,
    required this.translit,
    required this.meaning,
    this.note = '',
  });
}

/// ধাপের কাউন্টার: তাওয়াফ বা সাঈ
enum UmrahCounter { none, tawaf, sai }

class UmrahStep {
  final String id;
  final String emoji;
  final String title;
  final String subtitle;

  /// "এখন কী করবেন" — ক্রমানুসারে
  final List<String> points;

  /// নারীদের জন্য আলাদা নির্দেশনা (খালি থাকলে দেখাবে না)
  final List<String> womenPoints;

  /// ধাপের লাল সতর্কতা
  final List<String> warnings;

  /// এই ধাপে যেসব দোয়া পড়বেন (UmrahDua.id)
  final List<String> duaIds;
  final UmrahCounter counter;

  const UmrahStep({
    required this.id,
    required this.emoji,
    required this.title,
    required this.subtitle,
    required this.points,
    this.womenPoints = const [],
    this.warnings = const [],
    this.duaIds = const [],
    this.counter = UmrahCounter.none,
  });
}

class UmrahProblem {
  final String question;
  final String answer;
  const UmrahProblem(this.question, this.answer);
}

